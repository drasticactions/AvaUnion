namespace AvaUnion.Engine;

/// <summary>The alignment of an item.</summary>
public enum UnionAlignment
{
    /// <summary>Not specified.</summary>
    Unspecified,

    /// <summary>At the start.</summary>
    Start,

    /// <summary>Centered.</summary>
    Center,

    /// <summary>At the end.</summary>
    End,

    /// <summary>Fills the available space.</summary>
    Fill,

    /// <summary>Stacked vertically and centered.</summary>
    StackCenter,

    /// <summary>Stacked vertically and fills the available space.</summary>
    StackFill,
}
