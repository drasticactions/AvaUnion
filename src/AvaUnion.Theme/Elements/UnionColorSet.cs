namespace AvaUnion.Elements;

/// <summary>A short form for the <c>colorset</c> attribute that Breeze uses in its selectors.</summary>
public enum UnionColorSet
{
    /// <summary>No attribute.</summary>
    None,

    /// <summary><c>colorset=view</c>.</summary>
    View,

    /// <summary><c>colorset=window</c>.</summary>
    Window,

    /// <summary><c>colorset=button</c>.</summary>
    Button,

    /// <summary><c>colorset=selection</c>.</summary>
    Selection,

    /// <summary><c>colorset=tooltip</c>.</summary>
    Tooltip,

    /// <summary><c>colorset=complementary</c>.</summary>
    Complementary,

    /// <summary><c>colorset=header</c>.</summary>
    Header,
}
