#:property ImplicitUsings=enable

using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;

var check = args.Contains("--check");
var root = FindRoot();
var union = Path.Combine(root, "external/union");

var pinned = File.ReadLines(Path.Combine(union, "CMakeLists.txt"))
    .First(l => l.StartsWith("set(PROJECT_VERSION ", StringComparison.Ordinal))
    .Split('"')[1];

var releases = new List<(string Version, string Schema)>();
foreach (var tag in Git(["tag", "--list", "v*"])!.Split('\n', StringSplitOptions.RemoveEmptyEntries))
{
    if (CompareVersions(tag[1..], pinned) > 0)
    {
        continue;
    }

    var yml = Git(["show", $"{tag}:tools/propertygenerator/properties.yml"], allowFailure: true);
    if (yml is null)
    {
        continue;
    }

    var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(yml.Replace("\r\n", "\n")))).ToLowerInvariant();
    releases.Add((tag[1..], hash));
}

if (releases.Count == 0)
{
    Console.Error.WriteLine("external/union has no release tags; run git -C external/union fetch --tags");
    return 1;
}

releases.Sort((a, b) => CompareVersions(a.Version, b.Version));

var outputs = new Dictionary<string, string>
{
    ["src/AvaUnion.Theme/Engine/Native/UnionSchemas.g.cs"] = EmitCs(),
    ["native/src/UnionSchemas.g.h"] = EmitH(),
};

var stale = 0;
foreach (var (rel, text) in outputs)
{
    var full = Path.Combine(root, rel);
    var existing = File.Exists(full) ? File.ReadAllText(full) : null;
    if (existing == text)
    {
        continue;
    }

    if (check)
    {
        Console.Error.WriteLine($"stale: {rel}");
        stale++;
        continue;
    }

    File.WriteAllText(full, text);
    Console.WriteLine($"wrote {rel}");
}

if (check && stale > 0)
{
    return 1;
}

Console.WriteLine($"{releases.Count} releases, {releases.Select(r => r.Schema).Distinct().Count()} schemas");
return 0;

string EmitCs()
{
    var sb = new StringBuilder();
    sb.Append("// <auto-generated>\n");
    sb.Append("// Generated by tools/union-schemas from the tags of external/union. Do not edit.\n");
    sb.Append("// </auto-generated>\n\n");
    sb.Append("namespace AvaUnion.Engine.Native;\n\n");
    sb.Append("internal static class UnionSchemas\n{\n");
    sb.Append("    public static readonly (string Version, string Schema)[] Releases =\n    [\n");
    foreach (var (version, schema) in releases)
    {
        sb.Append($"        (\"{version}\", \"{schema}\"),\n");
    }

    sb.Append("    ];\n}\n");
    return sb.ToString();
}

string EmitH()
{
    var sb = new StringBuilder();
    sb.Append("/* Generated by tools/union-schemas from the tags of external/union. Do not edit. */\n");
    sb.Append("#pragma once\n\n");
    sb.Append("struct avu_union_release {\n    const char *version;\n    const char *schema;\n};\n\n");
    sb.Append("static const avu_union_release avu_union_releases[] = {\n");
    foreach (var (version, schema) in releases)
    {
        sb.Append($"    {{\"{version}\", \"{schema}\"}},\n");
    }

    sb.Append("};\n");
    return sb.ToString();
}

string? Git(string[] arguments, bool allowFailure = false)
{
    var start = new ProcessStartInfo("git") { RedirectStandardOutput = true, RedirectStandardError = true };
    start.ArgumentList.Add("-C");
    start.ArgumentList.Add(union);
    foreach (var a in arguments)
    {
        start.ArgumentList.Add(a);
    }

    using var process = Process.Start(start)!;
    var output = process.StandardOutput.ReadToEnd();
    process.WaitForExit();
    if (process.ExitCode != 0)
    {
        return allowFailure ? null : throw new InvalidOperationException($"git {string.Join(' ', arguments)} failed: {process.StandardError.ReadToEnd()}");
    }

    return output;
}

static int CompareVersions(string a, string b)
{
    var x = a.Split('.').Select(int.Parse).ToArray();
    var y = b.Split('.').Select(int.Parse).ToArray();
    for (var i = 0; i < Math.Min(x.Length, y.Length); i++)
    {
        if (x[i] != y[i])
        {
            return x[i].CompareTo(y[i]);
        }
    }

    return x.Length.CompareTo(y.Length);
}

static string FindRoot()
{
    var dir = Directory.GetCurrentDirectory();
    while (dir is not null && !File.Exists(Path.Combine(dir, "AvaUnion.slnx")))
    {
        dir = Path.GetDirectoryName(dir);
    }

    return dir ?? throw new InvalidOperationException("run from inside the repository");
}
